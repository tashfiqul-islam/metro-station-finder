/**
 * The public origin of the site (METRO-122): the one place that names it. `apps/web/index.html` is static, so
 * it carries `%SITE_ORIGIN%` where the canonical link, `og:url` and `og:image` need an absolute URL, and the
 * Vite plugin below swaps the token for this constant in the built page and in the dev server. Change the
 * origin here and nowhere else; `scripts/site-origin.test.ts` fails if the page repeats a literal origin.
 *
 * The owner holds metro-station-finder.com (apex canonical; `www` redirects to it, tracked separately). The
 * URL answers with the old scaffold until the first production deploy.
 */
export const SITE_ORIGIN = "https://metro-station-finder.com";

/** Where the share image is served from (generated by `build-brand-assets.ts`, never precached). */
export const OG_IMAGE_PATH = "/og/og-default.png";

/** The marker `index.html` uses for the origin. */
export const ORIGIN_TOKEN = "%SITE_ORIGIN%";

/** The page with every origin token replaced. A replacer function keeps any dollar sign in the origin literal. */
export const withSiteOrigin = (html: string): string =>
  html.replaceAll(ORIGIN_TOKEN, () => SITE_ORIGIN);

/** Vite plugin: replaces the token before Vite's own HTML processing, in build and in dev. */
export function siteOriginPlugin() {
  return {
    name: "metro-site-origin",
    transformIndexHtml: { order: "pre" as const, handler: withSiteOrigin },
  };
}
