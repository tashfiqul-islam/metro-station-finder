describe("baseline dataset v2 (legacy af903d7 plus METRO-67 corrections)", () => {
  test("is versioned and names its provenance", () => {
    expect(baselineDataset.version).toBe("baseline-v2");
    expect(baselineDataset.source).toContain("af903d7a2c1bf08165cfcf4a00ca0c0d73eedead");
  });

  test("passes the dataset validator", () => {
    expect(validateDataset(baselineDataset)).toEqual({ ok: true });
  });

  test("has 16 stations with unique ids, and no label shared by two stations", () => {
    expect(stations).toHaveLength(16);
    expect(new Set(stations.map((s) => s.id)).size).toBe(16);
    const labels = stations.flatMap((s) => [s.name, ...s.aliases]);
    expect(new Set(labels).size).toBe(labels.length);
  });

  test("fare table is 16x16 over the same station order, symmetric with a zero diagonal", () => {
    expect(fares.order).toEqual(stations.map((s) => s.id));
    expect(fares.amounts).toHaveLength(16);
    let cells = 0;
    fares.amounts.forEach((row, i) => {
      expect(row).toHaveLength(16);
      row.forEach((amount, j) => {
        cells += 1;
        expect(Number.isFinite(amount)).toBe(true);
        expect(fares.amounts[j]?.[i]).toBe(amount);
        expect(amount === 0).toBe(i === j);
      });
    });
    expect(cells).toBe(256);
  });

  test("every legacy label, from both legacy arrays, resolves to the station at its position", () => {
    stations.forEach((s, i) => {
      expect(resolveStation(stations, legacyCoordinateLabels[i] ?? "missing")).toBe(s);
      expect(resolveStation(stations, legacyFareLabels[i] ?? "missing")).toBe(s);
    });
  });

  test("equals the legacy snapshot except the three documented deviations", () => {
    const ids: string[] = stations.map((s) => s.id);
    expect(ids).toEqual(legacyStations.map(([id]) => id as string));
    const drift: unknown[] = [];
    legacyStations.forEach(([id, name, lat, lng], i) => {
      const s = stations[i];
      if (s?.name !== name) drift.push({ id, field: "name", legacy: name, now: s?.name });
      if (s?.coordinate.lat !== lat || s.coordinate.lng !== lng)
        drift.push({ id, field: "coordinate", legacy: { lat, lng }, now: s?.coordinate });
    });
    expect(drift).toEqual(deviations);
    expect(deviations).toHaveLength(3);
  });

  test("all 256 fare cells equal the legacy matrix, with no fare deviation", () => {
    expect(fares.amounts.map((row) => Array.from(row))).toEqual(
      legacyFares.map((row) => Array.from(row)),
    );
  });

  test("aliases are exactly the reviewed set", () => {
    for (const s of stations) expect([...s.aliases]).toEqual([...(aliasesById[s.id] ?? [])]);
  });

  test("display names are the corrected spellings and ids stay permanent", () => {
    const byId = new Map(stations.map((s) => [s.id as string, s]));
    expect(byId.get("shahbagh")?.name).toBe("Shahbag");
    expect(byId.get("bijoy-sharani")?.name).toBe("Bijoy Sarani");
    expect(resolveStation(stations, "Bijoy Sarawni")).toBe(byId.get("bijoy-sharani"));
  });

  test("the corrected Bijoy Sarani point is its own nearest, and the legacy point still maps to it", () => {
    const own = findNearestStation(stations, { lat: 23.7663936, lng: 90.3830971 });
    expect(own.kind === "nearest" ? own.station.id : own.kind).toBe(stationId("bijoy-sharani"));
    const near = findNearestStation(stations, { lat: 23.76767563448402, lng: 90.38309390581901 });
    expect(near.kind === "nearest" ? near.station.id : near.kind).toBe(stationId("bijoy-sharani"));
  });

  test("keeps legacy ordering, endpoints and fares", () => {
    expect(stations[0]).toMatchObject({
      id: "uttara-north",
      coordinate: { lat: 23.869076247909604, lng: 90.36749888965423 },
    });
    expect(stations[15]).toMatchObject({
      id: "motijheel",
      coordinate: { lat: 23.728141228055236, lng: 90.41934126299398 },
    });
    const [uttara, motijheel] = [stationId("uttara-north"), stationId("motijheel")];
    expect(findFare(fares, uttara, motijheel)).toEqual({
      kind: "fare",
      fare: { amount: 100, currency: "BDT" },
    });
    expect(findFare(fares, uttara, uttara)).toEqual({
      kind: "fare",
      fare: { amount: 0, currency: "BDT" },
    });
  });

  test("every station is its own nearest station at distance zero", () => {
    for (const s of stations) {
      const result = findNearestStation(stations, s.coordinate);
      expect(result.kind === "nearest" && result.station.id).toBe(s.id);
      expect(result.kind === "nearest" ? Number(result.distance) : -1).toBe(0);
    }
  });
});
